- (NSString *)getVersion {
    // libnclaw_version → *const c_char (static — DO NOT free).
    const char *raw = libnclaw_version();
    return (raw != NULL) ? [NSString stringWithUTF8String:raw] : @"unknown";
}

- (nullable NativeDeviceKeypairState *)keypairGenerate:(NSError **)error {
    __block FfiDeviceKeypair *kp = NULL;
    dispatch_sync(_ffiQueue, ^{
        kp = libnclaw_keypair_generate();
    });
    if (kp == NULL) {
        __block NSError *capturedError = nil;
        dispatch_sync(_ffiQueue, ^{
            capturedError = nclawCaptureError(@"keypairGenerate failed");
        });
        if (error) *error = capturedError;
        return nil;
    }
    return [[NativeDeviceKeypairState alloc] initWithKeypair:kp];
}

- (nullable NSString *)keypairPublicB64:(NativeDeviceKeypairState *)kp
                                   error:(NSError **)error {
    __block char *raw = NULL;
    dispatch_sync(_ffiQueue, ^{
        raw = libnclaw_keypair_public_b64(kp.keypair);
    });
    if (raw == NULL) {
        __block NSError *capturedError = nil;
        dispatch_sync(_ffiQueue, ^{
            capturedError = nclawCaptureError(@"keypairPublicB64 failed");
        });
        if (error) *error = capturedError;
        return nil;
    }
    // Copy caller-owned string to NSString, then free Rust allocation.
    NSString *result = [NSString stringWithUTF8String:raw];
    libnclaw_free_string(raw);
    return result;
}

- (nullable NativeSessionCipherState *)keypairDh:(NativeDeviceKeypairState *)kp
                                      remotePubB64:(NSString *)remotePubB64
                                             error:(NSError **)error {
    const char *remoteCStr = [remotePubB64 UTF8String];
    __block FfiSessionCipher *cipher = NULL;
    dispatch_sync(_ffiQueue, ^{
        cipher = libnclaw_keypair_dh(kp.keypair, remoteCStr);
    });
    if (cipher == NULL) {
        __block NSError *capturedError = nil;
        dispatch_sync(_ffiQueue, ^{
            capturedError = nclawCaptureError(@"keypairDh failed — check remotePubB64 base64 format");
        });
        if (error) *error = capturedError;
        return nil;
    }
    return [[NativeSessionCipherState alloc] initWithCipher:cipher];
}

