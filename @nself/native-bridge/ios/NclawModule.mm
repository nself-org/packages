/**
 * NativeDeviceKeypairState — wraps FfiDeviceKeypair* for NativeState lifecycle.
 *
 * Destructor calls libnclaw_keypair_free to release Rust-allocated memory.
 * JS GC → ObjC dealloc → libnclaw_keypair_free — no manual free needed in JS.
 */
@interface NativeDeviceKeypairState : NSObject
@property (nonatomic, readonly) FfiDeviceKeypair *keypair;
- (instancetype)initWithKeypair:(FfiDeviceKeypair *)keypair;
@end

@implementation NativeDeviceKeypairState

- (instancetype)initWithKeypair:(FfiDeviceKeypair *)keypair {
    if ((self = [super init])) {
        _keypair = keypair;
    }
    return self;
}

- (void)dealloc {
    if (_keypair != NULL) {
        libnclaw_keypair_free(_keypair);
        _keypair = NULL;
    }
}

@end

