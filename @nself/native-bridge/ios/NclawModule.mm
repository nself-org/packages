/**
 * @nself/native-bridge — NclawModule iOS Objective-C++ implementation.
 *
 * Purpose: Bridges libnclaw Rust C-ABI functions to React Native JSI via
 *          react-native-nitro-modules on iOS. Implements every FFI symbol
 *          from FFI audit §5 Groups A–D.
 *
 * Inputs:  libnclaw.h (cbindgen-generated from nclaw/core/src/lib.rs)
 *          ios/libs/libnclaw.a (Rust static library — built by scripts/build.sh)
 *
 * Outputs: NclawModule registered NitroModule ("NclawModule").
 *
 * Thread model:
 *   - _ffiQueue: private serial dispatch_queue_t — all Rust FFI calls run here.
 *   - JS calls arrive on JS thread → async_dispatch to _ffiQueue → resolve/reject.
 *   - libnclaw_last_error() called on _ffiQueue immediately after failing call.
 *   - Battery + thermal monitoring on main thread → dispatches setters to _ffiQueue.
 *
 * Memory rules (RF-01, §3):
 *   - *const c_char returns (libnclaw_last_error, libnclaw_version): copy to
 *     NSString immediately. DO NOT free — static/thread-local lifetime.
 *   - *mut c_char returns (keypair_public_b64, cipher_encrypt, cipher_decrypt):
 *     copy to NSString, then call libnclaw_free_string immediately.
 *   - *mut FfiDeviceKeypair, *mut FfiSessionCipher: wrapped in NativeState.
 *     NativeState destructor calls libnclaw_keypair_free / libnclaw_cipher_free.
 *
 * Cross-ref: T-P3-E4-W1-S1-T02 (FFI audit — memory rules in §3)
 *            ios/libs/nclaw.h (cbindgen-generated)
 *            scripts/build.sh (cross-compile script)
 */

