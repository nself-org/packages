// ---------------------------------------------------------------------------
// Primary chat + memory surface
//
// These convenience methods delegate to the Rust core's chat + memory pipeline.
// All run on _ffiQueue; resolve/reject blocks are called from _ffiQueue.
// nclaw/mobile's NitroModules glue lifts these into JS Promise<T>.
// ---------------------------------------------------------------------------

- (void)chatSend:(NSString *)message
          resolve:(void (^)(NSString *response))resolve
           reject:(void (^)(NSError *error))reject {
    const char *msgCStr = [message UTF8String];
    dispatch_async(_ffiQueue, ^{
        char *raw = nclaw_chat_send(msgCStr);
        if (raw == NULL) {
            NSError *err = nclawCaptureError(@"chatSend failed");
            reject(err);
            return;
        }
        NSString *response = [NSString stringWithUTF8String:raw];
        libnclaw_free_string(raw);
        resolve(response ?: @"");
    });
}

- (void)memorySearch:(NSString *)query
               limit:(NSInteger)limit
             resolve:(void (^)(NSString *json))resolve
              reject:(void (^)(NSError *error))reject {
    const char *queryCStr = [query UTF8String];
    int32_t limitI32 = (int32_t)MAX(0, MIN(limit, INT32_MAX));
    dispatch_async(_ffiQueue, ^{
        char *raw = nclaw_memory_search(queryCStr, limitI32);
        if (raw == NULL) {
            NSError *err = nclawCaptureError(@"memorySearch failed");
            reject(err);
            return;
        }
        NSString *json = [NSString stringWithUTF8String:raw];
        libnclaw_free_string(raw);
        resolve(json ?: @"[]");
    });
}

- (void)memoryInsert:(NSString *)messageJson
             resolve:(void (^)(void))resolve
              reject:(void (^)(NSError *error))reject {
    const char *jsonCStr = [messageJson UTF8String];
    dispatch_async(_ffiQueue, ^{
        bool ok = nclaw_memory_insert(jsonCStr);
        if (!ok) {
            NSError *err = nclawCaptureError(@"memoryInsert failed");
            reject(err);
            return;
        }
        resolve();
    });
}

- (void)memoryReplaceId:(NSString *)memId
             messageJson:(NSString *)messageJson
                 resolve:(void (^)(void))resolve
                  reject:(void (^)(NSError *error))reject {
    const char *idCStr = [memId UTF8String];
    const char *jsonCStr = [messageJson UTF8String];
    dispatch_async(_ffiQueue, ^{
        bool ok = nclaw_memory_replace(idCStr, jsonCStr);
        if (!ok) {
            NSError *err = nclawCaptureError(@"memoryReplace failed");
            reject(err);
            return;
        }
        resolve();
    });
}

