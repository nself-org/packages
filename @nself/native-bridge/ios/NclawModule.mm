static NSString *const kNclawErrorDomain = @"com.nself.nclaw";

/**
 * Capture the current libnclaw thread-local error string as an NSError.
 *
 * MUST be called on _ffiQueue immediately after a failing FFI call.
 * libnclaw_last_error() is thread-local — calling from any other thread
 * returns NULL (RF-01 from FFI audit §7).
 */
static NSError *nclawCaptureError(NSString *fallback) {
    const char *raw = libnclaw_last_error();
    NSString *msg = (raw != NULL)
        ? [NSString stringWithUTF8String:raw]  // thread-local — no free needed
        : fallback;
    return [NSError errorWithDomain:kNclawErrorDomain
                               code:-1
                           userInfo:@{NSLocalizedDescriptionKey: msg}];
}

// ---------------------------------------------------------------------------
// NclawModule implementation
// ---------------------------------------------------------------------------

@implementation NclawModule {
    dispatch_queue_t _ffiQueue;
    id<NSObject> _batteryObserver;
    id<NSObject> _thermalObserver;
}

- (instancetype)init {
    if ((self = [super init])) {
        _ffiQueue = dispatch_queue_create(
            "com.nself.nclaw.ffi",
            DISPATCH_QUEUE_SERIAL
        );
        [self _startPlatformMonitoring];
    }
    return self;
}

- (void)dealloc {
    [self _stopPlatformMonitoring];
}

// ---------------------------------------------------------------------------
// Platform monitoring (battery + thermal → damper setters)
// ---------------------------------------------------------------------------

- (void)_startPlatformMonitoring {
    // Enable battery monitoring for UIDevice.batteryLevel (RF-06).
    [UIDevice currentDevice].batteryMonitoringEnabled = YES;

    __weak NclawModule *weakSelf = self;

    _batteryObserver = [[NSNotificationCenter defaultCenter]
        addObserverForName:UIDeviceBatteryLevelDidChangeNotification
                    object:nil
                     queue:[NSOperationQueue mainQueue]
                usingBlock:^(NSNotification *note) {
        float level = [UIDevice currentDevice].batteryLevel;
        if (level >= 0) {
            uint8_t pct = (uint8_t)(level * 100.0f);
            [weakSelf setBatteryPct:pct];
        }
    }];

    _thermalObserver = [[NSNotificationCenter defaultCenter]
        addObserverForName:NSProcessInfoThermalStateDidChangeNotification
                    object:nil
                     queue:[NSOperationQueue mainQueue]
                usingBlock:^(NSNotification *note) {
        NSProcessInfoThermalState state = [NSProcessInfo processInfo].thermalState;
        uint8_t level = 0;
        switch (state) {
            case NSProcessInfoThermalStateNominal:  level = 0; break;
            case NSProcessInfoThermalStateFair:     level = 1; break;
            case NSProcessInfoThermalStateSerious:  level = 2; break;
            case NSProcessInfoThermalStateCritical: level = 3; break;
        }
        [weakSelf setThermalLevel:level];
    }];
}

- (void)_stopPlatformMonitoring {
    if (_batteryObserver) {
        [[NSNotificationCenter defaultCenter] removeObserver:_batteryObserver];
    }
    if (_thermalObserver) {
        [[NSNotificationCenter defaultCenter] removeObserver:_thermalObserver];
    }
    [UIDevice currentDevice].batteryMonitoringEnabled = NO;
}

